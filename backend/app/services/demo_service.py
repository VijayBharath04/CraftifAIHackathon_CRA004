import math
import time
import uuid
from typing import List, Dict, Any, Tuple
from datetime import datetime, timezone, timedelta
from ..models import EventModel, DetectedPerson, ZoneModel
from ..database import db

class DemoScenarioEngine:
    """
    Generates synthetic, deterministic trajectories to demonstrate
    AI Guardian when cameras or live inference are not running.
    Every generated event is unambiguously tagged with `is_demo=True`
    and prefixed with '[DEMO]'.
    """
    def __init__(self):
        self.step = 0
        self.scenario_tick = 0
        self.last_demo_event_time = 0.0

    def generate_demo_frame(self, zones: List[ZoneModel]) -> Tuple[List[DetectedPerson], str, List[EventModel]]:
        self.scenario_tick += 1
        now_iso = datetime.now(timezone.utc).isoformat()
        current_time = time.time()

        # Simulate a walking person along a trajectory in normalized coordinates [0..1]
        # Period: 30 ticks cycle
        # Ticks 1..10: Person outside (GREEN)
        # Ticks 11..18: Person approaching warning buffer (YELLOW)
        # Ticks 19..26: Person breaches restricted zone (RED)
        # Ticks 27..30: Person exits back to outside (GREEN)
        cycle = self.scenario_tick % 36
        
        detections: List[DetectedPerson] = []
        new_events: List[EventModel] = []
        risk_state = "GREEN"

        active_zone = next((z for z in zones if z.enabled), None)
        zone_name = active_zone.name if active_zone else "Demo Vault Zone"
        zone_id = active_zone.id if active_zone else "zone_demo"

        if cycle < 10:
            # Person far outside
            x = 0.10 + (cycle * 0.01)
            y = 0.15 + (cycle * 0.01)
            risk_state = "GREEN"
            detections.append(DetectedPerson(
                id=101,
                bbox=[x - 0.04, y - 0.12, x + 0.04, y],
                confidence=0.91,
                reference_point=[x, y],
                status="OUTSIDE",
                zone_name=None,
                zone_id=None
            ))
        elif cycle < 18:
            # Approaching warning buffer
            x = 0.22 + ((cycle - 10) * 0.015)
            y = 0.28 + ((cycle - 10) * 0.012)
            risk_state = "YELLOW"
            detections.append(DetectedPerson(
                id=101,
                bbox=[x - 0.04, y - 0.12, x + 0.04, y],
                confidence=0.94,
                reference_point=[x, y],
                status="WARNING",
                zone_name=zone_name,
                zone_id=zone_id
            ))
        elif cycle < 28:
            # Inside Restricted Zone
            x = 0.38 + ((cycle - 18) * 0.012)
            y = 0.45 + ((cycle - 18) * 0.010)
            risk_state = "RED"
            detections.append(DetectedPerson(
                id=101,
                bbox=[x - 0.05, y - 0.14, x + 0.05, y],
                confidence=0.96,
                reference_point=[x, y],
                status="INSIDE_RESTRICTED",
                zone_name=zone_name,
                zone_id=zone_id
            ))
            # Trigger demo event on initial entry (at cycle 19)
            if cycle == 19 and (current_time - self.last_demo_event_time > 4.0):
                self.last_demo_event_time = current_time
                demo_event = EventModel(
                    event_id=f"demo_evt_{uuid.uuid4().hex[:8]}",
                    event_type="RESTRICTED_ZONE_ENTRY",
                    zone=f"[DEMO] {zone_name}",
                    zone_id=zone_id,
                    severity="HIGH",
                    person_count=1,
                    confidence=0.96,
                    timestamp=now_iso,
                    is_demo=True,
                    details={"simulation_note": "Generated by AI Guardian Demo Scenario Engine"}
                )
                saved = db.save_event(demo_event)
                new_events.append(saved)
        else:
            # Exited
            x = 0.82 + ((cycle - 28) * 0.02)
            y = 0.80
            risk_state = "GREEN"
            detections.append(DetectedPerson(
                id=101,
                bbox=[x - 0.04, y - 0.12, x + 0.04, y],
                confidence=0.88,
                reference_point=[x, y],
                status="OUTSIDE",
                zone_name=None,
                zone_id=None
            ))

        return detections, risk_state, new_events

    def seed_demo_history(self, count: int = 8):
        """Seeds realistic demonstration events across past hours if event table is empty."""
        existing = db.get_events(limit=5, is_demo=True)
        if len(existing) > 0:
            return

        now = datetime.now(timezone.utc)
        demo_zones = [
            ("Perimeter Restricted Zone", "HIGH"),
            ("Server Room Restricted Perimeter", "CRITICAL"),
            ("Chemical Storage Zone", "HIGH"),
            ("Loading Bay Safety Corridor", "MEDIUM")
        ]

        for i in range(count):
            past_time = now - timedelta(minutes=(i * 18) + 5)
            z_name, sev = demo_zones[i % len(demo_zones)]
            evt = EventModel(
                event_id=f"demo_hist_{uuid.uuid4().hex[:8]}",
                event_type="RESTRICTED_ZONE_ENTRY",
                zone=f"[DEMO] {z_name}",
                zone_id=f"zone_{i}",
                severity=sev,
                person_count=1 if i % 4 != 0 else 2,
                confidence=round(0.85 + (i * 0.015) % 0.12, 2),
                timestamp=past_time.isoformat(),
                acknowledged=(i > 2),  # Keep recent ones unacknowledged
                acknowledged_at=(past_time + timedelta(minutes=2)).isoformat() if i > 2 else None,
                is_demo=True,
                details={"simulation_note": "Sample operational event for dashboard walkthrough"}
            )
            db.save_event(evt)

demo_engine = DemoScenarioEngine()
